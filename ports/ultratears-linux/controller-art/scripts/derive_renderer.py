"""Derive only rendering primitives/text/art from retained source snapshots.

No network, game files, key files, or repository mutation. Writes this directory's
generated steamdeck_renderer.c only. Sources and their hashes are in sources.json.
"""
from pathlib import Path
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--original-front', action='store_true', help='test-only original D-pad geometry')
parser.add_argument('--output', type=Path, help='output C file, inside this source directory')
args = parser.parse_args()
destination = (ROOT/args.output).resolve() if args.output else ROOT/'steamdeck_renderer.c'
if not destination.is_relative_to(ROOT):
    parser.error('--output must remain inside the source directory')
for item in json.loads((ROOT / 'sources.json').read_text()):
    assert hashlib.sha256((ROOT / item['path']).read_bytes()).hexdigest() == item['sha256']
glyph = (ROOT / 'vendor/glyphs.upstream.c').read_text()
art = (ROOT / 'vendor/botw_xbox_diagram.original.inc').read_text()
# Keep precisely the SDF primitives needed by the original authored artwork.
geom = glyph[glyph.index('typedef enum { SH_CIRCLE'):glyph.index('static void fill(Canvas')]
geom += glyph[glyph.index('static Shape circle('):glyph.index('// ---- text')]
geom = geom[:geom.index('static Shape tri(')] + geom[geom.index('static Shape ring('):]
text = glyph[glyph.index('static void text('):glyph.index('static void ink(')]
text = text.replace('static void text(Canvas *t,', 'static void text(sd_renderer *ctx, Canvas *t,')
text = text.replace('if (!font_ready() || !*s)', 'if (!*s)')
text = text.replace('&g_font', '&ctx->font')
text = text.replace('static unsigned char bm[', 'unsigned char bm[')
paint = art[art.index('static void deck_paint('):art.index('static void deck_draw(')]
paint = paint.replace('static void deck_word(uint8_t *lin,', 'static void deck_word(sd_renderer *ctx,uint8_t *lin,')
paint = paint.replace('text(&c,label,', 'text(ctx,&c,label,')
front = art.split('if(h==288) {', 1)[1].split('} else {', 1)[0]
# V2: Valve's front diagram puts the D-pad center slightly ABOVE the stick,
# not below it. Match that ~9px gap while retaining the existing sticks/ABXY.
# Four exact cross primitives move together; original vendor snapshot is frozen.
assert front.count('box(38,65,') == 4
if not args.original_front:
    front = front.replace('box(38,65,', 'box(38,79,')
top = art.split('} else {', 1)[1].split('\n    }\n    #undef DP', 1)[0]
prefix = '''/* Generated by scripts/derive_renderer.py; see NOTICE.md.
 * Geometry/text derived from SavageWind runtime/nvn/glyphs.c (MIT).
 * Authored device art retained from botw_xbox_diagram.inc. */
#include "steamdeck_renderer.h"
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <math.h>
#include <limits.h>
#define STBTT_STATIC
#define STB_TRUETYPE_IMPLEMENTATION
#if defined(__clang__)
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wunused-function"
#elif defined(__GNUC__)
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wunused-function"
#endif
#include "vendor/imstb_truetype.h"
#if defined(__clang__)
#pragma clang diagnostic pop
#elif defined(__GNUC__)
#pragma GCC diagnostic pop
#endif
#define CELL 50
typedef struct { float a[CELL * CELL]; } Canvas;
struct sd_renderer { stbtt_fontinfo font; unsigned char *font_data; };
'''
draws = ''
for name, body, h in [('front', front, 288), ('top', top, 100)]:
    draws += f'''\nstatic void draw_{name}_rg8(sd_renderer *ctx,uint8_t *lin) {{
    const uint32_t w=576,h={h},row=1152;
    memset(lin,0,(size_t)row*h);
    #define DP(shape,grey) deck_paint(lin,row,w,h,(shape),(grey))
    #define DW(x,y,s,cap,mw) deck_word(ctx,lin,row,w,h,x,y,s,cap,mw)
{body}
    #undef DP
    #undef DW
}}
'''
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text(prefix + geom + text + paint + draws + '\n#include "inclined_view.inc"\n#include "renderer_api.inc"\n')
print('Derived steamdeck_renderer.c from hash-verified public/source snapshots')
